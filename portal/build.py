#!/usr/bin/env python3
"""Build the on-device Wi-Fi setup page.

Inlines tokens.css + components.css + app.js + logo.svg into index.html, gzips it and writes
components/noqopen_portal/portal_page.h. Run after editing anything in portal/:

    python3 portal/build.py            # writes the header
    python3 portal/build.py --html out # also writes the inlined page for a browser preview
    python3 portal/build.py --check    # fails if portal_page.h is not built from the current sources (CI)
"""
import gzip
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent
OUT = ROOT.parent / "components" / "noqopen_portal" / "portal_page.h"


def css(text: str) -> str:
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    text = re.sub(r"\s+", " ", text)
    text = re.sub(r"\s*([{};,>])\s*", r"\1", text)
    return text.replace(";}", "}").strip()


def js(text: str) -> str:
    lines = [ln.strip() for ln in text.splitlines()]
    return "\n".join(ln for ln in lines if ln and not ln.startswith("//"))


def logo(text: str) -> str:
    text = re.sub(r"<\?xml.*?\?>", "", text)
    text = re.sub(r"<defs>.*?</defs>", "", text, flags=re.S)
    text = re.sub(r'\s(id|data-name)="[^"]*"', "", text)
    text = text.replace('class="cls-1"', 'fill="#a3e635"')
    text = text.replace("<svg ", '<svg class="np-logo" aria-hidden="true" ', 1)
    text = re.sub(r">\s+<", "><", text)
    return text.strip()


def page() -> str:
    html = (ROOT / "index.html").read_text(encoding="utf-8")
    style = css((ROOT / "tokens.css").read_text(encoding="utf-8") + (ROOT / "components.css").read_text(encoding="utf-8"))
    html = html.replace("/*CSS*/", style)
    html = html.replace("<!--LOGO-->", logo((ROOT / "logo.svg").read_text(encoding="utf-8")))
    html = html.replace("/*JS*/", js((ROOT / "app.js").read_text(encoding="utf-8")))
    return re.sub(r">\s+<", "><", html).strip()


def header(data: bytes) -> str:
    rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 20]) for i in range(0, len(data), 20)]
    body = ",\n    ".join(rows)
    return (
        "#pragma once\n"
        "// Generated by portal/build.py. Do not edit; change portal/ and rebuild.\n\n"
        '#include "esphome/core/hal.h"\n\n'
        "namespace esphome::noqopen_portal {\n\n"
        f"constexpr uint8_t PAGE_GZ[] PROGMEM = {{\n    {body}}};\n\n"
        "}  // namespace esphome::noqopen_portal\n"
    )


def committed() -> str:
    data = bytes(int(x, 16) for x in re.findall(r"0x([0-9a-f]{2})", OUT.read_text(encoding="utf-8")))
    return gzip.decompress(data).decode("utf-8")


def main() -> None:
    html = page()
    if "--check" in sys.argv:
        if committed() != html:
            sys.exit("portal_page.h is out of date: run python3 portal/build.py and commit it")
        print("portal_page.h is up to date")
        return
    data = gzip.compress(html.encode("utf-8"), compresslevel=9, mtime=0)
    OUT.write_text(header(data), encoding="utf-8")
    if "--html" in sys.argv:
        target = pathlib.Path(sys.argv[sys.argv.index("--html") + 1])
        target.write_text(html, encoding="utf-8")
    print(f"portal: {len(html)} bytes html, {len(data)} bytes gzip -> {OUT.relative_to(ROOT.parent)}")


if __name__ == "__main__":
    main()
